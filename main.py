def main():
    # Step 1: Load API key.
    load_dotenv()

    # Step 2: Init the AI Agent
    print("\n LinkedIn Post Generator")
    print("--------------------------")
    
    try:
        agent = LinkedInPostGenerator()
    except Exception as e:
        print(f" Error: {e}")
        return
    
    # Step 3: Get user input
    topic = input(" Enter post topic: ").strip()
    language = input(" Enter language (e.g., English, Bengali, Spanish): ").strip()
    
    if not topic or not language:
        print(" Topic and language are required.")
        return

    # Step 4: Generate the post
    print("\n Generating your post... Please wait.\n")
    try:
        post = agent.generate_post(topic, language)
    except Exception as error:
        print(" Failed to generate post:")
        print(str(error))
        return
    
    # Step 5: Save files
    text_file_path = save_post_to_file(post, language)
    html_file_path = save_post_to_html(post, language)
    html_abs_path = os.path.abspath(html_file_path)

    # Step 6: Display output summary
    print(" Post generated successfully!")
    print(f"   Language: {language}")
    print(f"   Length:   {len(post)} characters, {len(post.split())} words")
    print()
    
    print(f" Files saved:")
    print(f"    Text: {text_file_path}")
    print(f"    HTML: {html_file_path}")

    # Always auto-open the HTML in the default browser
    print("\n Opening your post in the browser...")
    webbrowser.open(f"file://{html_abs_path}")
    print(f"   If it didn't open, manually open:\n   {html_abs_path}")

if __name__ == "__main__":
    main()
