def save_post_to_file(post: str, language: str) -> str:
    safe_lang = language.strip().lower().replace(" ", "_") or "output"
    output_path = f"linkedin_post_{safe_lang}.txt"
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(post)
    return output_path


